"""
Export utilities — generate DOCX and PDF transcripts.
Both functions accept SQLAlchemy ORM objects directly.
"""

from datetime import datetime


# ─── Shared helpers ───────────────────────────────────────────────────────────

_SPEAKER_COLORS = ["#2B6CB0", "#276749", "#553C9A", "#744210", "#1A202C"]


def _speaker_color(idx: int) -> str:
    return _SPEAKER_COLORS[min(idx, len(_SPEAKER_COLORS) - 1)]


def _fmt_ts(seconds: float) -> str:
    m = int(seconds // 60)
    s = int(seconds % 60)
    return f"{m:02d}:{s:02d}"


def _fmt_duration(seconds: float) -> str:
    if not seconds:
        return "0:00"
    h = int(seconds // 3600)
    m = int((seconds % 3600) // 60)
    s = int(seconds % 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"


def _hex_to_rgb(h: str) -> tuple:
    h = h.lstrip("#")
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4))


# ─── DOCX ─────────────────────────────────────────────────────────────────────

def generate_txt(segments, include_timestamps: bool = True) -> str:
    lines = []
    for seg in segments:
        spk_name = seg.speaker.display_name if seg.speaker else "Speaker"
        if include_timestamps:
            lines.append(f"[{_fmt_ts(seg.start)}] {spk_name}: {seg.text}")
        else:
            lines.append(f"{spk_name}: {seg.text}")
    return "\n".join(lines)


def generate_docx(job, segments, speakers, action_items, output_path: str, include_timestamps: bool = True):
    from docx import Document
    from docx.shared import Pt, Inches, RGBColor
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement

    def rgb(hex_color: str) -> RGBColor:
        r, g, b = _hex_to_rgb(hex_color)
        return RGBColor(r, g, b)

    def set_cell_bg(cell, fill_hex: str):
        tc = cell._tc
        tcPr = tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:fill"), fill_hex.lstrip("#"))
        shd.set(qn("w:val"), "clear")
        tcPr.append(shd)

    doc = Document()

    # Page margins
    section = doc.sections[0]
    section.top_margin    = Inches(1)
    section.bottom_margin = Inches(1)
    section.left_margin   = Inches(1)
    section.right_margin  = Inches(1)

    # Footer: filename left, page number right
    footer_para = section.footer.paragraphs[0]
    footer_para.clear()
    p_pPr = footer_para._p.get_or_add_pPr()
    tabs = OxmlElement("w:tabs")
    tab_el = OxmlElement("w:tab")
    tab_el.set(qn("w:val"), "right")
    tab_el.set(qn("w:pos"), "9360")  # 6.5 in × 1440 twips/in
    tabs.append(tab_el)
    p_pPr.append(tabs)

    r_left = footer_para.add_run(job.filename)
    r_left.font.size = Pt(8)
    r_left.font.color.rgb = rgb("#718096")
    footer_para.add_run("\t")
    r_pg = footer_para.add_run()
    r_pg.font.size = Pt(8)
    r_pg.font.color.rgb = rgb("#718096")
    for el_xml in [
        ("w:fldChar", {"w:fldCharType": "begin"}),
        ("w:instrText", {"_text": "PAGE"}),
        ("w:fldChar", {"w:fldCharType": "end"}),
    ]:
        tag, attrs = el_xml
        el = OxmlElement(tag)
        for k, v in attrs.items():
            if k == "_text":
                el.text = v
            else:
                el.set(qn(k), v)
        r_pg._r.append(el)

    # Title
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(4)
    r = p.add_run(job.filename)
    r.bold = True
    r.font.size = Pt(18)
    r.font.color.rgb = rgb("#2D3748")

    # Metadata subtitle
    date_str  = job.created_at.strftime("%B %d, %Y") if job.created_at else datetime.now().strftime("%B %d, %Y")
    meta_text = (
        f"Generated by WhisperX Pipeline  |  {date_str}  |  {job.language or 'unknown'}  |  {_fmt_duration(job.duration or 0)}"
        if include_timestamps
        else f"Generated by WhisperX Pipeline  |  {date_str}  |  {job.language or 'unknown'}"
    )
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(8)
    r = p.add_run(meta_text)
    r.font.size = Pt(9)
    r.font.color.rgb = rgb("#718096")

    # Horizontal rule via paragraph border
    rule = doc.add_paragraph()
    rule.paragraph_format.space_after = Pt(12)
    pPr = rule._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "4")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "E2E8F0")
    pBdr.append(bottom)
    pPr.append(pBdr)

    # "Transcript" heading
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(8)
    r = p.add_run("Transcript")
    r.bold = True
    r.font.size = Pt(14)
    r.font.color.rgb = rgb("#2D3748")

    # Speaker index for color assignment
    speaker_list  = list(speakers)
    speaker_index = {sp.id: i for i, sp in enumerate(speaker_list)}

    for seg in segments:
        sp_idx   = speaker_index.get(seg.speaker_id, 0) if seg.speaker_id else 0
        color    = _speaker_color(sp_idx)
        ts_str   = _fmt_ts(seg.start)
        spk_name = seg.speaker.display_name if seg.speaker else "Speaker"

        # Speaker name + optional timestamp line
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(4)
        p.paragraph_format.space_after  = Pt(0)
        r = p.add_run(spk_name)
        r.bold = True
        r.font.size = Pt(10)
        r.font.color.rgb = rgb(color)
        if include_timestamps:
            r2 = p.add_run(f"  {ts_str}")
            r2.font.size = Pt(9)
            r2.font.color.rgb = rgb("#718096")

        # Segment text, indented
        p2 = doc.add_paragraph()
        p2.paragraph_format.left_indent = Inches(0.3)
        p2.paragraph_format.space_after = Pt(4)
        p2.add_run(seg.text).font.size  = Pt(10)

    # Action Items section
    action_list = list(action_items)
    if action_list:
        doc.add_paragraph()
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(8)
        r = p.add_run("Action Items")
        r.bold = True
        r.font.size = Pt(14)
        r.font.color.rgb = rgb("#2D3748")

        _pri_colors = {"high": "#E53E3E", "medium": "#D69E2E", "normal": "#718096"}

        hdr_labels = ["Task", "Assignee", "Priority", "Due Date"] + (["Time"] if include_timestamps else [])
        table = doc.add_table(rows=1, cols=len(hdr_labels), style="Table Grid")

        # Header row
        hdr = table.rows[0].cells
        for i, label in enumerate(hdr_labels):
            p_cell = hdr[i].paragraphs[0]
            r = p_cell.add_run(label)
            r.bold = True
            r.font.size = Pt(10)
            r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
            set_cell_bg(hdr[i], "2D3748")

        # Data rows
        for row_idx, item in enumerate(action_list):
            row = table.add_row()
            bg   = "F7FAFC" if row_idx % 2 == 0 else "FFFFFF"
            vals = [item.text or "", item.assignee or "", item.priority or "normal", item.due_date or ""]
            if include_timestamps:
                vals.append(item.timestamp or "")
            for col_idx, val in enumerate(vals):
                cell = row.cells[col_idx]
                r = cell.paragraphs[0].add_run(val)
                r.font.size = Pt(10)
                if col_idx == 2:
                    r.font.color.rgb = rgb(_pri_colors.get(val, "#718096"))
                set_cell_bg(cell, bg)

    doc.save(output_path)


# ─── PDF ──────────────────────────────────────────────────────────────────────

def generate_pdf(job, segments, speakers, action_items, output_path: str, include_timestamps: bool = True):
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.units import inch
    from reportlab.lib.colors import HexColor, white
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.enums import TA_RIGHT
    from reportlab.platypus import (
        SimpleDocTemplate, Paragraph, Spacer, HRFlowable, Table, TableStyle,
    )
    from reportlab.pdfgen import canvas as rl_canvas

    PAGE_W, _PAGE_H = A4
    MARGIN = inch

    def hc(h: str) -> HexColor:
        return HexColor(h)

    # Two-pass canvas for "Page X of Y"
    class _NumberedCanvas(rl_canvas.Canvas):
        def __init__(self, *args, **kwargs):
            rl_canvas.Canvas.__init__(self, *args, **kwargs)
            self._pages: list = []

        def showPage(self):
            self._pages.append(dict(self.__dict__))
            self._startPage()

        def save(self):
            total = len(self._pages)
            for state in self._pages:
                self.__dict__.update(state)
                self._draw_footer(total)
                rl_canvas.Canvas.showPage(self)
            rl_canvas.Canvas.save(self)

        def _draw_footer(self, total: int):
            self.setFont("Helvetica", 9)
            self.setFillColor(hc("#718096"))
            self.drawCentredString(
                PAGE_W / 2, 0.5 * inch,
                f"Page {self._pageNumber} of {total}",
            )

    SPEAKER_COLORS_PDF = ["#2B6CB0", "#276749", "#553C9A", "#744210", "#1A202C"]

    title_style = ParagraphStyle("TitleP", fontName="Helvetica-Bold", fontSize=18, textColor=hc("#2D3748"), spaceAfter=4)
    meta_style  = ParagraphStyle("MetaP",  fontName="Helvetica",      fontSize=9,  textColor=hc("#718096"), spaceAfter=8)
    h2_style    = ParagraphStyle("H2P",    fontName="Helvetica-Bold", fontSize=14, textColor=hc("#2D3748"), spaceBefore=16, spaceAfter=8)
    body_style  = ParagraphStyle("BodyP",  fontName="Helvetica",      fontSize=10, textColor=hc("#1A202C"), leftIndent=20, spaceAfter=6)
    ts_style    = ParagraphStyle("TSP",    fontName="Helvetica",      fontSize=8,  textColor=hc("#718096"), alignment=TA_RIGHT, spaceAfter=0)
    spk_base    = ParagraphStyle("SpkBase", spaceAfter=0)

    story    = []
    usable_w = PAGE_W - 2 * MARGIN

    # Title
    story.append(Paragraph(job.filename, title_style))

    # Metadata
    date_str     = job.created_at.strftime("%B %d, %Y") if job.created_at else datetime.now().strftime("%B %d, %Y")
    speaker_list = list(speakers)
    sp_count     = len(speaker_list)
    sp_label     = f"{sp_count} speaker{'s' if sp_count != 1 else ''}"
    meta_text    = (
        f"{date_str}  ·  {job.language or 'unknown'}  ·  {_fmt_duration(job.duration or 0)}  ·  {sp_label}"
        if include_timestamps
        else f"{date_str}  ·  {job.language or 'unknown'}  ·  {sp_label}"
    )
    story.append(Paragraph(meta_text, meta_style))

    # HR
    story.append(HRFlowable(width="100%", thickness=0.5, color=hc("#E2E8F0"), spaceAfter=12))

    # Transcript heading
    story.append(Paragraph("Transcript", h2_style))

    speaker_index = {sp.id: i for i, sp in enumerate(speaker_list)}

    for seg in segments:
        sp_idx   = speaker_index.get(seg.speaker_id, 0) if seg.speaker_id else 0
        color    = SPEAKER_COLORS_PDF[min(sp_idx, len(SPEAKER_COLORS_PDF) - 1)]
        ts_str   = _fmt_ts(seg.start)
        spk_name = seg.speaker.display_name if seg.speaker else "Speaker"

        spk_para = Paragraph(
            f'<font name="Helvetica-Bold" color="{color}" size="10">{spk_name}</font>',
            spk_base,
        )
        if include_timestamps:
            # Speaker name (left) + timestamp (right) in a mini table
            ts_para = Paragraph(
                f'<font name="Helvetica" color="#718096" size="8">{ts_str}</font>',
                ts_style,
            )
            row_tbl = Table([[spk_para, ts_para]], colWidths=[usable_w - 60, 60])
            row_tbl.setStyle(TableStyle([
                ("VALIGN",        (0, 0), (-1, -1), "BOTTOM"),
                ("TOPPADDING",    (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
                ("LEFTPADDING",   (0, 0), (-1, -1), 0),
                ("RIGHTPADDING",  (0, 0), (-1, -1), 0),
            ]))
            story.append(row_tbl)
        else:
            story.append(spk_para)
        story.append(Paragraph(seg.text, body_style))

    # Action Items
    action_list = list(action_items)
    if action_list:
        story.append(Spacer(1, 12))
        story.append(Paragraph("Action Items", h2_style))

        _pcolors = {"high": "#E53E3E", "medium": "#D69E2E", "normal": "#718096"}
        if include_timestamps:
            col_widths = [220, 90, 70, 90, 60]
            tdata = [["Task", "Assignee", "Priority", "Due Date", "Time"]]
            for item in action_list:
                tdata.append([item.text or "", item.assignee or "", item.priority or "normal", item.due_date or "", item.timestamp or ""])
        else:
            col_widths = [250, 100, 80, 100]
            tdata = [["Task", "Assignee", "Priority", "Due Date"]]
            for item in action_list:
                tdata.append([item.text or "", item.assignee or "", item.priority or "normal", item.due_date or ""])

        ai_tbl = Table(tdata, colWidths=col_widths)
        tbl_style = TableStyle([
            ("BACKGROUND",    (0, 0), (-1, 0), hc("#2D3748")),
            ("TEXTCOLOR",     (0, 0), (-1, 0), white),
            ("FONTNAME",      (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE",      (0, 0), (-1, -1), 10),
            ("GRID",          (0, 0), (-1, -1), 0.5, hc("#E2E8F0")),
            ("VALIGN",        (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING",    (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("LEFTPADDING",   (0, 0), (-1, -1), 8),
            ("RIGHTPADDING",  (0, 0), (-1, -1), 8),
        ])
        for i in range(1, len(tdata)):
            bg = "#F7FAFC" if i % 2 == 1 else "#FFFFFF"
            tbl_style.add("BACKGROUND", (0, i), (-1, i), hc(bg))
        for i, item in enumerate(action_list, start=1):
            pc = _pcolors.get(item.priority or "normal", "#718096")
            tbl_style.add("TEXTCOLOR", (2, i), (2, i), hc(pc))
            tbl_style.add("FONTNAME",  (2, i), (2, i), "Helvetica-Bold")
        ai_tbl.setStyle(tbl_style)
        story.append(ai_tbl)

    doc = SimpleDocTemplate(
        output_path,
        pagesize=A4,
        topMargin=MARGIN,
        bottomMargin=MARGIN,
        leftMargin=MARGIN,
        rightMargin=MARGIN,
    )
    doc.build(story, canvasmaker=_NumberedCanvas)
